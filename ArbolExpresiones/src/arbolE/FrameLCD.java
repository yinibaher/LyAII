        public void generaEmutasm(String emu, String nombre){
        try{
            String ruta = System.getProperty("user.home") + File.separator + "Downloads";
            File archivo = new File(ruta, nombre + ".asm");            

            FileWriter escritor = new FileWriter(archivo);
            escritor.write(emu);
            escritor.close();

            System.out.println("Archivo .asm creado exitosamente");
                    
            ProcessBuilder pb = new ProcessBuilder("C:\\emu8086\\emu8086.exe", archivo.getAbsolutePath());
        pb.start();
        }
        catch(Exception e){
            System.out.println("Ha ocurrido un error al crear el archivo");
        }
    }//generaEmu
        
    public void Sonido(){
        try {
            File sonido = new File("src/arbolE/notification.wav");
            if (sonido.exists()) {
                AudioInputStream audioStream = AudioSystem.getAudioInputStream(sonido);
                Clip clip = AudioSystem.getClip();
                clip.open(audioStream);
                clip.start(); 
            } else {
                showMessageDialog(null, "No se encontró el archivo de sonido.");
            }
        } catch (Exception e) {
            e.printStackTrace();
            showMessageDialog(null, "Error al reproducir el sonido.");
        }
    }//sonido

