    private void jbtnExportarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnExportarActionPerformed
        archivo = jtxtArchivo.getText();
        mensaje = jtxtEnvio.getText();
        longitud = mensaje.length();
        
        codigo = 
                """
                ; IBARRA HERNANDEZ JEANELY FERNANDA - LCD01.asm
                .MODEL SMALL 
                .STACK 
                .MODEL SMALL 
                .DATA
                    MENSAJE DB '""" + mensaje + "' ; LONG "+ longitud +"\n" +                          
                 
                """
                .CODE
                    MOV AX,@DATA
                    MOV DS, AX

                    MOV SI,0     ; INDICE
                    MOV CX,"""+ longitud + "\n" +
                """
                    MOV DX,2040H ; PUERTO INICIAL DE LCD

                LABEL01:  
                    MOV AL,MENSAJE[SI]
                    OUT DX,AL    ; ENVIAR HACIA EL PUERTO DEL CONTENIDO DE <AL>
                    INC SI
                    INC DX
                    LOOP LABEL01         

                    MOV AX,4C00H
                    INT 21H  
                 END
                """;
        
        jTextArea.setText(codigo);
        generaEmutasm(codigo,archivo);
        
        LocalTime hora = LocalTime.now();
        DateTimeFormatter formato = DateTimeFormatter.ofPattern("HH:mm:ss");

        String horaActual = hora.format(formato);
        lblHora.setText("Hora envío: " + horaActual);
        Sonido();
        
    }//GEN-LAST:event_jbtnExportarActionPerformed

